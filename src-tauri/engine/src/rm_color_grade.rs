//! RAWmakase's colour grading: Lightroom's Color Grading (and its older Split
//! Toning) as Camera Raw 18.7 renders it, measured.
//!
//! Camera Raw grades each channel of linear ProPhoto RGB with its own curve: a
//! channel's output depends on that channel's input only. A region's tint gains
//! are 1 + sum of A_k(x) p_k, with profiles A along the channel value that
//! Blending and Balance shape, and per-channel coefficients p that hue and
//! saturation set; regions multiply. Luminance is one curve for all channels,
//! applied before the tint. RAWmakase fitted the profiles and coefficients to
//! Camera Raw's renders of a colour chart (`rm_color_grade_curves.tsv`,
//! generated by scripts/rawmakase-grade-curves.mjs from their
//! `color_grade_curves.bin`; their docs/color-mixer.md, "Color grading").
//!
//! `gains` turns one grading into 64 gains per channel, once per edit; the
//! app's renderer looks each channel up in them on the GPU (`rm_grade` in
//! src-tauri/src/shaders/modules.wgsl, from src-tauri/src/mods/color_grade.rs),
//! and `apply` is the same lookup on the CPU.
//!
//! FROM RAWMAKASE
//!
//! RAWmakase `v0.4.1` @ 5a2414b4 (MIT), unchanged since `v0.4.0` @ a8c5d6d7:
//! - `crates/rawmakase-engine/src/develop/color_grade_curves.rs`: the tables'
//!   layout, `profiles`, `coefficients`, `luminance_log`, `weight`, `argmax`,
//!   `sample`, `encoded`, `luminance`, `gains`, `ChannelCurves::apply`, and
//!   their tests.
//! - `crates/rawmakase-engine/src/develop/color_grade.rs`: the test
//!   `blue_shadow_tint_cools_shadows_more_than_highlights`.
//! - `crates/rawmakase-engine/src/develop/parametric.rs`: `bracket`.
//!
//! WHAT CHANGED IN THE COPY
//!
//! - The grading comes in as a `Grading` rather than their `Recipe`.
//! - A profile look's split toning, their second pass (`compose`), is left
//!   out: no profile here carries one.
//! - The tables are read from text, as the repository keeps no binaries.

use std::sync::OnceLock;

/// Samples of each curve over E = x^(1/2.2), 0 to 1.
pub const SAMPLES: usize = 64;
const BLENDS: [f32; 5] = [0., 0.25, 0.5, 0.75, 1.];
const BALANCES: [f32; 17] = [
    -1., -0.88, -0.75, -0.62, -0.5, -0.38, -0.25, -0.12, 0., 0.12, 0.25, 0.38, 0.5, 0.62, 0.75,
    0.88, 1.,
];
const HUES: usize = 12;
const SATURATIONS: [f32; 5] = [0., 0.25, 0.5, 0.75, 1.];
/// Luminance slider positions, 0 being no change.
const LUMINANCES: [f32; 9] = [-1., -0.75, -0.5, -0.25, 0., 0.25, 0.5, 0.75, 1.];
/// Profile terms per region; Global's third is used by Global only.
const TERMS: usize = 3;
const SHAPED_TERMS: usize = 2;

// Offsets in values, in the order the tables are written.
const GRID: usize = 0;
const GRID_LEN: usize = 3 * BLENDS.len() * BALANCES.len() * SAMPLES * SHAPED_TERMS;
const GLOBAL: usize = GRID + GRID_LEN;
const COEF: usize = GLOBAL + SAMPLES * TERMS;
const COEF_LEN: usize = 4 * HUES * (SATURATIONS.len() - 1) * 3 * TERMS;
const LUM: usize = COEF + COEF_LEN;
const LEN: usize = LUM + 4 * (LUMINANCES.len() - 1) * SAMPLES;

/// Columns before a row's values: what was measured, the region, two settings.
const LABELS: usize = 4;

/// The tables, `LEN` values. Empty if they do not read, which a test rules
/// out; grading then changes nothing.
fn data() -> &'static [f32] {
    static DATA: OnceLock<Vec<f32>> = OnceLock::new();
    DATA.get_or_init(|| parse(include_str!("rm_color_grade_curves.tsv")).unwrap_or_default())
}

/// The values of the tables' text, in the binary's order.
fn parse(text: &str) -> Result<Vec<f32>, String> {
    let mut values = Vec::with_capacity(LEN);
    for (i, line) in text.lines().enumerate() {
        if line.starts_with('#') || line.is_empty() {
            continue;
        }
        for field in line.split('\t').skip(LABELS) {
            let v: f32 = field
                .parse()
                .map_err(|_| format!("rm_color_grade_curves.tsv line {}: {field}", i + 1))?;
            values.push(v);
        }
    }
    if values.len() != LEN {
        return Err(format!(
            "rm_color_grade_curves.tsv holds {} values, not {LEN}",
            values.len()
        ));
    }
    Ok(values)
}

fn value(i: usize) -> f32 {
    data()[i]
}

/// One grading as Lightroom stores it, in RAWmakase's units.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Grading {
    /// Shadows, Midtones, Highlights and Global, each hue (a turn, 0 to 1),
    /// saturation (0 to 1) and luminance (-1 to 1).
    pub regions: [[f32; 3]; 4],
    /// 0 to 1; Lightroom's default is 0.5.
    pub blending: f32,
    /// -1 to 1.
    pub balance: f32,
}

impl Default for Grading {
    fn default() -> Self {
        Self {
            regions: [[0.; 3]; 4],
            blending: 0.5,
            balance: 0.,
        }
    }
}

/// Per-channel gains of linear ProPhoto RGB at `SAMPLES` points of x^(1/2.2).
pub type Gains = [[f32; 3]; SAMPLES];

// from RAWmakase crates/rawmakase-engine/src/develop/parametric.rs @ 5a2414b4, `bracket`.
/// The bracketing positions of `v` in `values` (clamped to their range) and the
/// weight of the upper one.
fn bracket(values: &[f32], v: f32) -> (usize, f32) {
    let v = v.clamp(values[0], values[values.len() - 1]);
    let j = values
        .windows(2)
        .position(|w| v <= w[1])
        .unwrap_or(values.len() - 2);
    (j, (v - values[j]) / (values[j + 1] - values[j]))
}

// What follows, to `apply`, is from RAWmakase
// crates/rawmakase-engine/src/develop/color_grade_curves.rs @ 5a2414b4.

/// Shadows, Midtones, Highlights and Global, as `Grading` orders them.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Region {
    Shadows,
    Midtones,
    Highlights,
    Global,
}
const REGIONS: [Region; 4] = [
    Region::Shadows,
    Region::Midtones,
    Region::Highlights,
    Region::Global,
];

/// Where Blending and Balance put a region's tint: its profiles at every sample.
type Profiles = [[f32; TERMS]; SAMPLES];

fn profiles(region: Region, blending: f32, balance: f32) -> Profiles {
    let mut out = [[0.; TERMS]; SAMPLES];
    if region == Region::Global {
        for (k, p) in out.iter_mut().enumerate() {
            *p = std::array::from_fn(|t| value(GLOBAL + k * TERMS + t));
        }
        return out;
    }
    let (i, u) = bracket(&BLENDS, blending);
    let (j, v) = bracket(&BALANCES, balance);
    let at = |b: usize, a: usize, k: usize, t: usize| {
        let cell = ((region as usize * BLENDS.len() + b) * BALANCES.len() + a) * SAMPLES + k;
        value(GRID + cell * SHAPED_TERMS + t)
    };
    for (k, p) in out.iter_mut().enumerate() {
        for (t, slot) in p.iter_mut().enumerate().take(SHAPED_TERMS) {
            *slot = at(i, j, k, t) * (1. - u) * (1. - v)
                + at(i + 1, j, k, t) * u * (1. - v)
                + at(i, j + 1, k, t) * (1. - u) * v
                + at(i + 1, j + 1, k, t) * u * v;
        }
    }
    out
}

/// The region's per-channel coefficients for `hue` (0 to 1, a turn) and `saturation` (0 to 1).
fn coefficients(region: Region, hue: f32, saturation: f32) -> [[f32; TERMS]; 3] {
    let f = hue.rem_euclid(1.) * HUES as f32;
    let (h0, w) = ((f as usize) % HUES, f.fract());
    let (s, u) = bracket(&SATURATIONS, saturation);
    // Saturation 0 has no tint; the table starts at 25.
    let at = |h: usize, s: usize, c: usize, t: usize| match s {
        0 => 0.,
        s => {
            let i = (((region as usize * HUES + h) * (SATURATIONS.len() - 1) + s - 1) * 3 + c)
                * TERMS
                + t;
            value(COEF + i)
        }
    };
    std::array::from_fn(|c| {
        std::array::from_fn(|t| {
            let hue_at = |s| at(h0, s, c, t) * (1. - w) + at((h0 + 1) % HUES, s, c, t) * w;
            hue_at(s) * (1. - u) + hue_at(s + 1) * u
        })
    })
}

/// log2 of the measured Luminance gains at `amount` (-1 to 1), Blending 50 and Balance 0.
fn luminance_log(region: Region, amount: f32) -> [f32; SAMPLES] {
    let (j, u) = bracket(&LUMINANCES, amount);
    let table = |i: usize| -> [f32; SAMPLES] {
        match i.cmp(&4) {
            std::cmp::Ordering::Equal => [0.; SAMPLES],
            order => {
                let row = if order == std::cmp::Ordering::Less {
                    i
                } else {
                    i - 1
                };
                let at = LUM + (region as usize * (LUMINANCES.len() - 1) + row) * SAMPLES;
                std::array::from_fn(|k| value(at + k).log2())
            }
        }
    };
    let (a, b) = (table(j), table(j + 1));
    std::array::from_fn(|k| a[k] * (1. - u) + b[k] * u)
}

/// The region's first profile, scaled to peak at 1: where it sits along the channel.
fn weight(region: Region, blending: f32, balance: f32) -> [f32; SAMPLES] {
    let p = profiles(region, blending, balance);
    let peak = p
        .iter()
        .map(|t| t[0])
        .fold(0f32, |m, v| if v.abs() > m.abs() { v } else { m });
    std::array::from_fn(|k| if peak == 0. { 0. } else { p[k][0] / peak })
}

fn argmax(v: &[f32]) -> usize {
    (0..v.len()).fold(0, |m, i| if v[i] > v[m] { i } else { m })
}

/// Linear interpolation of `table` at fractional sample `at`.
fn sample(table: &[f32; SAMPLES], at: f32) -> f32 {
    let at = at.clamp(0., (SAMPLES - 1) as f32);
    let i = (at as usize).min(SAMPLES - 2);
    let t = at - i as f32;
    table[i] * (1. - t) + table[i + 1] * t
}

fn encoded(k: usize) -> f32 {
    k as f32 / (SAMPLES - 1) as f32
}

/// The Luminance gains at `amount`, Blending and Balance: Luminance keeps the strength
/// it has at the default where the region's weight is the same, on the same side of
/// the weight's peak. Darkening keeps its gain there, lifts their encoded offset.
fn luminance(region: Region, amount: f32, blending: f32, balance: f32) -> [f32; SAMPLES] {
    let log = luminance_log(region, amount);
    let default = (blending - 0.5).abs() < 1e-4 && balance.abs() < 1e-4;
    if region == Region::Global || default {
        return log.map(f32::exp2);
    }
    let (w, w0) = (weight(region, blending, balance), weight(region, 0.5, 0.));
    let (peak, peak0) = (argmax(&w), argmax(&w0));
    let at: [f32; SAMPLES] = std::array::from_fn(|k| {
        let side = if k <= peak {
            0..peak0 + 1
        } else {
            peak0..SAMPLES
        };
        let seg: Vec<usize> = side.collect();
        let near = (0..seg.len())
            .min_by(|&a, &b| {
                (w0[seg[a]] - w[k])
                    .abs()
                    .total_cmp(&(w0[seg[b]] - w[k]).abs())
            })
            .unwrap_or(0);
        for (a, b) in [(near.wrapping_sub(1), near), (near, near + 1)] {
            if a < seg.len() && b < seg.len() {
                let (lo, hi) = (w0[seg[a]], w0[seg[b]]);
                if (lo - w[k]) * (hi - w[k]) <= 0. && lo != hi {
                    let t = (w[k] - lo) / (hi - lo);
                    return seg[a] as f32 + t * (seg[b] as f32 - seg[a] as f32);
                }
            }
        }
        seg[near] as f32
    });
    if amount < 0. {
        return std::array::from_fn(|k| sample(&log, at[k]).exp2());
    }
    let offset: [f32; SAMPLES] = std::array::from_fn(|k| encoded(k) * ((log[k] / 2.2).exp2() - 1.));
    std::array::from_fn(|k| match k {
        0 => log[0].exp2(),
        k => ((encoded(k) + sample(&offset, at[k])) / encoded(k)).powf(2.2),
    })
}

/// The grading curves of `grading`, or `None` when it changes nothing (no
/// region has a tint or a Luminance change), or the tables did not read.
pub fn gains(grading: &Grading) -> Option<Gains> {
    let Grading {
        regions: settings,
        blending,
        balance,
    } = *grading;
    if settings.iter().all(|g| g[1] == 0. && g[2] == 0.) || data().is_empty() {
        return None;
    }
    let mut lum = [1f32; SAMPLES];
    let mut tint = [[1f32; 3]; SAMPLES];
    for (region, [hue, saturation, amount]) in REGIONS.into_iter().zip(settings) {
        if amount != 0. {
            let l = luminance(region, amount, blending, balance);
            lum.iter_mut().zip(l).for_each(|(a, b)| *a *= b);
        }
        if saturation != 0. {
            let p = profiles(region, blending, balance);
            let c = coefficients(region, hue, saturation);
            for (g, a) in tint.iter_mut().zip(p) {
                for (ch, coef) in g.iter_mut().zip(c) {
                    *ch *= 1. + a.iter().zip(coef).map(|(a, c)| a * c).sum::<f32>();
                }
            }
        }
    }
    // Luminance first, then the tint on its result.
    let tint: [[f32; SAMPLES]; 3] = std::array::from_fn(|c| std::array::from_fn(|i| tint[i][c]));
    Some(std::array::from_fn(|k| {
        let after = (encoded(k).powf(2.2) * lum[k]).clamp(0., 1.).powf(1. / 2.2);
        std::array::from_fn(|c| lum[k] * sample(&tint[c], after * (SAMPLES - 1) as f32).max(0.))
    }))
}

/// `p`, linear ProPhoto RGB, graded: each channel scaled by its gain at its
/// own value. RAWmakase's `ChannelCurves::apply`.
pub fn apply(gains: &Gains, p: [f32; 3]) -> [f32; 3] {
    std::array::from_fn(|c| {
        let v = p[c];
        let at = v.clamp(0., 1.).powf(1. / 2.2) * (SAMPLES - 1) as f32;
        let i = (at as usize).min(SAMPLES - 2);
        let t = at - i as f32;
        v * (gains[i][c] * (1. - t) + gains[i + 1][c] * t)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn graded(g: &Grading, p: [f32; 3]) -> [f32; 3] {
        apply(&gains(g).unwrap(), p)
    }

    fn with(region: usize, setting: [f32; 3]) -> Grading {
        let mut g = Grading::default();
        g.regions[region] = setting;
        g
    }

    #[test]
    fn the_tables_read_in_full() {
        assert_eq!(
            parse(include_str!("rm_color_grade_curves.tsv")).map(|v| v.len()),
            Ok(LEN)
        );
    }

    /// Gains RAWmakase's own `ChannelCurves::new` gives (color_grade_curves.rs
    /// @ 5a2414b4, compiled beside this copy), at four samples. The copy
    /// matched it bit for bit on 4,000 random gradings.
    #[test]
    fn gains_are_rawmakase_s() {
        // Each a grading and its gains at four samples.
        type Expected = [(usize, [f32; 3]); 4];
        let cases: [(Grading, Expected); 3] = [
            (
                // B&W > Sepia's split toning.
                Grading {
                    regions: [
                        [38. / 360., 0.25, 0.],
                        [0.; 3],
                        [45. / 360., 0.18, 0.],
                        [0.; 3],
                    ],
                    ..Grading::default()
                },
                [
                    (8, [1.1323988, 0.9441864, 0.62022364]),
                    (24, [1.0443861, 0.9822619, 0.87128156]),
                    (40, [1.0225463, 0.9909723, 0.9174191]),
                    (56, [1.0140523, 0.99448735, 0.94152254]),
                ],
            ),
            (
                // Creative > Faded Gold's.
                Grading {
                    regions: [[51. / 360., 0.17, 0.], [0.; 3], [0.; 3], [0.; 3]],
                    ..Grading::default()
                },
                [
                    (8, [1.0361863, 0.98422724, 0.69107664]),
                    (24, [1.0106262, 0.995711, 0.9143459]),
                    (40, [1.0023962, 0.9989677, 0.979723]),
                    (56, [1.0002118, 0.99990654, 0.9981747]),
                ],
            ),
            (
                // Every region, Luminance both ways, Blending and Balance off their defaults.
                Grading {
                    regions: [
                        [200. / 360., 0.6, -0.3],
                        [100. / 360., 0.4, 0.2],
                        [20. / 360., 0.8, 0.4],
                        [300. / 360., 0.1, -0.1],
                    ],
                    blending: 0.8,
                    balance: -0.35,
                },
                [
                    (8, [0.40676838, 0.8511883, 1.2455351]),
                    (24, [0.6189228, 1.0721644, 1.164185]),
                    (40, [1.0972025, 1.1313926, 0.8840821]),
                    (56, [1.1822261, 1.0126771, 0.9324509]),
                ],
            ),
        ];
        for (grading, expected) in cases {
            let g = gains(&grading).unwrap();
            for (k, want) in expected {
                assert_eq!(g[k], want, "{grading:?} at sample {k}");
            }
        }
    }

    #[test]
    fn no_grading_has_no_curves() {
        assert!(gains(&Grading::default()).is_none());
        // Blending and Balance alone move nothing.
        let g = Grading {
            blending: 0.9,
            balance: -0.4,
            ..Grading::default()
        };
        assert!(gains(&g).is_none());
        assert!(gains(&with(0, [240. / 360., 0.5, 0.])).is_some());
    }

    #[test]
    fn channels_are_graded_independently() {
        // Camera Raw's grading is a curve per channel: a channel's output doesn't depend
        // on the others.
        let g = with(0, [30. / 360., 0.5, 0.]);
        let a = graded(&g, [0.02, 0.3, 0.6]);
        let b = graded(&g, [0.02, 0.05, 0.9]);
        assert_eq!(a[0], b[0]);
        assert!(a[0] > 0.02 * 1.2, "{a:?}");
    }

    #[test]
    fn blue_shadow_tint_cools_shadows_more_than_highlights() {
        // A grey is the same in linear sRGB and linear ProPhoto.
        let g = with(0, [240. / 360., 0.5, 0.]);
        let cool = |p: [f32; 3]| p[2] / p[0].max(1e-6);
        let dark = graded(&g, [0.02; 3]);
        let bright = graded(&g, [0.8; 3]);
        assert!(cool(dark) > 1.05, "{dark:?}");
        assert!(cool(dark) > cool(bright));
    }

    #[test]
    fn balance_moves_shadows_up_the_range() {
        let mut g = with(0, [210. / 360., 0.5, 0.]);
        let blue = |g: &Grading| graded(g, [0.1; 3])[2] / 0.1;
        let at_default = blue(&g);
        g.balance = -1.;
        assert!(blue(&g) > at_default + 0.1, "{} {at_default}", blue(&g));
        g.balance = 1.;
        assert!(blue(&g) < at_default - 0.1);
    }

    #[test]
    fn blending_widens_the_regions() {
        let mut g = with(2, [40. / 360., 0.5, 0.]);
        let red = |g: &Grading| graded(g, [0.05; 3])[0] / 0.05;
        g.blending = 0.;
        let narrow = red(&g);
        g.blending = 1.;
        assert!(red(&g) > narrow + 0.02, "{} {narrow}", red(&g));
    }

    #[test]
    fn luminance_darkens_and_lifts_shadows() {
        let mut g = with(0, [0., 0., -0.5]);
        let dark = graded(&g, [0.01; 3]);
        assert!(
            dark.iter().all(|v| (v / 0.01 - 0.5).abs() < 0.1),
            "{dark:?}"
        );
        g.regions[0][2] = 0.5;
        assert!(graded(&g, [0.01; 3])[1] > 0.02);
        // Unchanged near white.
        assert!((graded(&g, [0.95; 3])[1] - 0.95).abs() < 0.01);
    }

    #[test]
    fn luminance_follows_blending_and_balance() {
        let mut g = with(0, [0., 0., -0.5]);
        let at = |g: &Grading| graded(g, [0.04; 3])[1] / 0.04;
        let default = at(&g);
        g.balance = 1.;
        assert!(at(&g) > default + 0.1);
        g.balance = 0.;
        g.blending = 1.;
        assert!(at(&g) < default);
    }
}
